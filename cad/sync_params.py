"""Generate params.scad from RobotConfig.

THE POINT OF THIS FILE

The controller and the physical robot have to agree on three lengths: hip
offset, thigh, shank. If they disagree, the IK is solving for a robot that
does not exist -- every foot lands somewhere other than where it was
commanded, and no amount of gain tuning fixes it because the error is
geometric, not dynamic.

Typing those numbers into the CAD by hand guarantees they eventually drift.
So they are generated. Change RobotConfig, re-run this, re-export the STLs,
and the hardware follows the model by construction.

Run:  python3 cad/sync_params.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

# The kinematics live in reference/ -- they are the design model the
# CAD is generated from, not firmware.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "reference"))

from quadruped.robot import Quadruped, RobotConfig, LEG_NAMES
from quadruped import transmission as TX
from quadruped.leg import JointLimits

M = 1000.0      # metres -> millimetres, because CAD works in mm


def main() -> None:
    robot = Quadruped()
    c = robot.config
    lim = JointLimits()

    # Shank section and foot. Tapered so the material sits where the
    # moment is; the ball radius also sets the ride height above.
    shank_w_knee, shank_w_foot, foot_r = 20.0, 13.0, 9.0

    # The pose the assembly is drawn in, and where it must put the foot.
    body, feet = robot.stand()
    pose_a = robot.solve(body, feet)["FL"]
    foot = robot.legs["FL"].fk_hip_frame(pose_a)

    # Leg outline. KNEE_R is the thigh's narrowest loaded section, so it
    # sets the safety factor in check_walls.py -- 12 mm came out at 1.9,
    # under the 2.0 target, and 14 mm costs almost nothing because the
    # knee boss is already there.
    # knee_r 15, not 14. It is the thigh's narrowest loaded section and
    # it sets the safety factor for the whole leg: at 14 the thigh's
    # knee end came out at 1.9 once the mass estimate caught up with
    # everything that had been added to make the robot stronger. 15
    # puts it back over 2 and costs 2 g.
    joint_bore_d, head_r, knee_r = 36.0, 21.0, 15.5
    truss_rail, truss_fillet = 3.5, 3.0

    out = Path(__file__).resolve().parent / "params.scad"
    L: list[str] = []
    w = L.append

    w("// GENERATED by cad/sync_params.py -- do not edit by hand.")
    w("// Kinematic values come from reference/quadruped/robot.py:RobotConfig.")
    w("// Re-run the script after changing RobotConfig.")
    w("")
    w("// ---------------------------------------------------------------")
    w("// KINEMATIC -- these three must match the controller exactly.")
    w("// Everything else is free; these are not.")
    w("// ---------------------------------------------------------------")
    w(f"HIP_OFFSET = {c.hip_offset*M:.1f};   // roll axis -> leg plane (== leg_plane below)")
    w(f"THIGH      = {c.thigh*M:.1f};  // hip pitch axis -> knee axis")
    w(f"SHANK      = {c.shank*M:.1f};  // knee axis -> FOOT BALL CENTRE")
    w(f"BODY_LEN   = {c.body_length*M:.1f};  // front roll axis -> rear roll axis")
    w(f"BODY_WID   = {c.body_width*M:.1f};  // left roll axis -> right roll axis")
    w("")
    w("// The foot is a ball, so SHANK ends at its CENTRE, not at the")
    w("// ground. A ball's contact point is always FOOT_R directly below")
    w("// its centre whatever angle the shank is at, so the IK solving to")
    w("// the centre is exactly right -- the robot simply stands FOOT_R")
    w("// higher than STAND_HEIGHT. Measured off the exported assembly,")
    w("// the four ball centres land within 0.02 mm of where the solver")
    w("// puts them.")
    chassis_t = 8.0
    hip_z = chassis_t + (20.0 + 2*3.0)/2      # roll servo lying on the plate
    # That expression says the servo lies on its SIDE: the plate's skin
    # plus half of (width + two walls). For a long time the drawn geometry
    # disagreed -- rotate([0,90,0]) alone stood the servo's 40 mm length
    # up instead, so each corner carried a 57 mm tower with the servo's
    # bottom 4 mm sunk into the plate. hip.scad's extra quarter turn is
    # what makes the model match this number.
    w("// Roll axis height above the underside of the chassis plate. The")
    w("// servo lies flat on the plate, so this is the plate's skin plus")
    w("// half the housing. ONE definition: chassis.scad builds to it,")
    w("// robot.scad places the legs at it, check_fit.py checks at it.")
    w(f"HIP_Z        = {hip_z:.1f};")
    w(f"STAND_HEIGHT = {c.stand_height*M:.1f};  // hip to ball centre")
    w(f"RIDE_HEIGHT  = {c.stand_height*M + foot_r:.1f};  // hip to the ground")
    w(f"MASS_EST     = {c.mass:.2f};    // kg, for the record")
    w("")
    w("// ---------------------------------------------------------------")
    w("// JOINT TRAVEL -- what the gait actually commands, measured across")
    w("// every gait and direction. Brackets must clear these or the leg")
    w("// hits itself mid-stride. Limits are the IK's hard stops.")
    w("// ---------------------------------------------------------------")
    w("ROLL_USED  = [-27.5,  27.5];   ROLL_LIMIT = "
      f"[{math.degrees(lim.roll[0]):.1f}, {math.degrees(lim.roll[1]):.1f}];")
    w("HIP_USED   = [-89.6,  16.9];   HIP_LIMIT  = "
      f"[{math.degrees(lim.hip[0]):.1f}, {math.degrees(lim.hip[1]):.1f}];")
    w("KNEE_USED  = [ 21.6, 115.1];   KNEE_LIMIT = [15.0, 150.0];")
    w("")
    w("// ---------------------------------------------------------------")
    w("// SERVO -- DS3225, standard size.")
    w("//")
    w("// MEASURE YOUR OWN BEFORE PRINTING TWELVE OF ANYTHING. Servo body")
    w("// size is near-universal for 'standard size', but the mounting")
    w("// flange hole pattern is NOT standardised between manufacturers.")
    w("// Calipers on one real servo, then correct the four SERVO_HOLE")
    w("// values below. This is a five-minute check that saves a failed")
    w("// print of every bracket on the robot.")
    w("// ---------------------------------------------------------------")
    w("SERVO_L = 40.0;    // body length")
    w("SERVO_W = 20.0;    // body width")
    w("SERVO_H = 40.4;    // body height, shaft face to bottom")
    w("SERVO_FLANGE_L  = 54.0;  // overall length across the mounting ears")
    w("SERVO_FLANGE_TH =  2.5;  // ear thickness")
    w("SERVO_FLANGE_Z  = 30.0;  // ear height above the body bottom")
    w("SERVO_HOLE_DX   = 49.5;  // hole spacing, lengthwise  <-- MEASURE")
    w("SERVO_HOLE_DY   = 10.0;  // hole spacing, crosswise   <-- MEASURE")
    w("SERVO_HOLE_D    =  4.2;  // hole diameter             <-- MEASURE")
    w("SERVO_SHAFT_OFF = 10.0;  // shaft offset from body centre, lengthwise")
    w("SERVO_SPLINE_D  =  5.92; // 25T spline outer diameter")
    w("SERVO_HORN_D    = 22.0;  // round horn diameter, for the pocket")
    w("SERVO_HORN_TH   =  2.0;")
    w("// Fit allowance on the servo's own pocket, on top of CLEAR.")
    w("//")
    w("// A \"standard size\" servo is NOT one size. Three listings for")
    w("// the same 25 kg class measure 40.0 x 20.5 x 40.5, 40.5 x 20.2 x")
    w("// 40.3 and 40.0 x 20.0 x 40.5, and a dimension drawing for the")
    w("// genuine DS3225MG gives 54.5 across the ears where this file")
    w("// said 54.0. Sized to any one of them, the pocket comes out 0.1")
    w("// mm oversize for the others -- which is less than the printer")
    w("// managed, so the servo simply will not go in.")
    w("//")
    w("// 0.6 takes a body up to 0.5 mm over nominal and still leaves")
    w("// 0.35 a side. The four mounting screws are what locate the")
    w("// servo, so slack in the pocket costs nothing.")
    w(f"SERVO_FIT       =  0.6;")
    w("")
    # ---------------------------------------------------------------
    # THE HIP STACK -- every lateral position, derived once from the roll
    # axis outward. Parts read these; they do not place themselves.
    #
    # THE RULE THAT KEEPS IT TIGHT: a servo's BODY goes on the far side of
    # its own joint, never between the joint and the robot's centre. Point
    # them inboard and each one adds its full 40.4 mm length to the
    # offset -- that is how HIP_OFFSET reached 102 mm and splayed the legs
    # out from under the robot.
    #
    #   pitch servo  horn inboard, body OUTBOARD  -> adds nothing
    #   knee servo   horn outboard, body inboard along the thigh, where
    #                there is nothing to clear
    # ---------------------------------------------------------------
    sv_h = 40.4
    plate_t, shank_t = 8.0, 8.0
    # Collar engagement, hip and knee, and they are not the same number.
    #
    # The hip one is the journal that keeps the leg's bending off the
    # pitch servo's output shaft, and it is the only thing doing that
    # job. At 4 mm a 240 mm leg reacted its side loads over 4 mm of a
    # 35 mm bearing. It is free to grow: trace the chain below and the
    # hip collar feeds only pitch_face, which feeds only the pitch
    # servo's own body -- and that body ends well inboard of where the
    # knee servo already reaches, so the robot gets no wider for it.
    #
    # The knee one IS in the chain that lands on the leg plane, so that
    # one is not free: every mm of it comes straight off the gap between
    # the roll collar and the thigh plate.
    hip_collar_h, knee_collar_h = 10.0, 7.0
    roll_half = 20.0                        # roll collar boss, half-width

    # The stack is built outward from the roll axis and has to LAND on
    # HIP_OFFSET, because that is the number the IK solves with. Working
    # inward from the leg plane gives the one free dimension -- the gap
    # between the roll collar and the thigh plate -- so the two can never
    # drift apart again.
    #
    #   leg_plane = roll_half + gap + plate_t + collar_h + shank_t/2
    #
    # It used to be a hardcoded 2 mm gap, which put the leg plane at
    # 38 mm while the controller aimed every foot at 40 mm.
    gap = c.hip_offset*M - roll_half - plate_t - knee_collar_h - shank_t/2
    if gap < 2.0:
        raise SystemExit(
            f"hip_offset {c.hip_offset*M:.1f} mm leaves only {gap:.1f} mm "
            f"between the roll collar and the thigh plate. Needs >= 2.0 mm; "
            f"raise RobotConfig.hip_offset to at least "
            f"{roll_half + 2.0 + plate_t + knee_collar_h + shank_t/2:.1f} mm.")

    # ---------------------------------------------------------------
    # LINKAGE BANDS. Crank and rocker share ONE plane -- a planar
    # four-bar is not planar otherwise -- and the rod sits beside them.
    #
    # The crank shares the SHANK's plane, which costs no width at all:
    # the rocker is a lug on the shank, and the crank is at C, 64 mm up
    # the thigh where the shank never reaches. Going outboard of the
    # shank instead would have cost 8 mm a side for nothing.
    #
    # The servo has to be outboard. Inboard was tried and the chassis is
    # in the way: it hangs 31 mm below the hip and reaches 21 mm outboard
    # of the roll axis, and the thigh sweeps the servo straight through
    # that for most of the hip's range. Measured, not guessed -- 1.6 cm3
    # of shared material at the standing pose alone.
    rod_t = 5.0
    # (link_in/link_out are the shank's own band; filled in below, once
    #  the stack has decided where that is.)

    thigh_in    = roll_half + gap           # thigh plate, inboard face
    thigh_out   = thigh_in + plate_t        # thigh plate, outboard face
    # Collar rings stand proud of the plate and run in bores, so they get
    # their own band -- the plate itself must stay clear of the bore's
    # outer boss or the two foul each other.
    hip_collar  = thigh_out                 # thigh collar ring, inboard end
    pitch_face  = hip_collar + hip_collar_h  # pitch servo shaft face
    pitch_out   = pitch_face + sv_h         # pitch servo body, outboard end
    knee_collar = thigh_out                 # shank collar ring, inboard end
    shank_in    = knee_collar + knee_collar_h   # shank plate, inboard face
    leg_plane   = shank_in + shank_t/2      # the foot

    # The linkage, now that the shank's band is known.
    link_in   = shank_in                    # crank + rocker share it
    link_out  = shank_in + shank_t
    rod_in    = link_out + 0.8
    rod_out   = rod_in + rod_t
    # The crank's boss has to carry the horn clear of the rod's plane,
    # and the feature that decides how far is not the horn (2 mm) or the
    # gearbox boss (3 mm) but the SPLINE, which stands 7 mm proud of the
    # shaft face. At full knee extension the rod's edge passes within a
    # millimetre of the shaft axis, so anything protruding that far
    # inboard is in its way. Those 7 mm set the robot's overall width.
    crank_hub = rod_out + 0.8 + 7.0
    knee_face = crank_hub                   # servo horn lands on that boss
    knee_in   = knee_face                   # body runs OUTBOARD from here
    knee_out  = knee_face + sv_h


    # Belt and braces: the derivation above should make this exact.
    assert abs(leg_plane - c.hip_offset*M) < 1e-9, (
        f"leg plane {leg_plane:.3f} mm != hip_offset {c.hip_offset*M:.3f} mm")

    w("// ---------------------------------------------------------------")
    w("// HIP STACK. A servo's body always sits on the FAR side of its own")
    w("// joint -- never between that joint and the robot's centre, or it")
    w("// adds its whole 40.4 mm length to HIP_OFFSET.")
    w("// ---------------------------------------------------------------")
    w(f"ROLL_HALF   = {roll_half:.1f};   // roll collar boss, +/- this")
    w(f"THIGH_IN    = {thigh_in:.1f};   // thigh plate, inboard face")
    w(f"THIGH_OUT   = {thigh_out:.1f};   // thigh plate, outboard face")
    w(f"HIP_COLLAR  = {hip_collar:.1f};   // thigh collar ring, inboard end")
    w(f"KNEE_COLLAR = {knee_collar:.1f};   // shank collar ring, inboard end")
    w(f"PITCH_FACE  = {pitch_face:.1f};   // pitch servo shaft face (horn inboard)")
    w(f"PITCH_OUT   = {pitch_out:.1f};   // pitch servo body, outboard end")
    w(f"KNEE_FACE   = {knee_face:.1f};   // knee servo shaft face, on the crank boss")
    w(f"KNEE_OUT    = {knee_out:.1f};   // knee servo body, outboard end")
    w(f"LINK_IN     = {link_in:.1f};   // crank + rocker plane (the shank's own)")
    w(f"LINK_OUT    = {link_out:.1f};   // crank + rocker plane, outboard face")
    w(f"ROD_IN      = {rod_in:.1f};   // pushrod plane, inboard face")
    w(f"ROD_OUT     = {rod_out:.1f};   // pushrod plane, outboard face")
    w(f"CRANK_HUB   = {crank_hub:.1f};   // crank boss, outboard face")
    w(f"SHANK_IN    = {shank_in:.1f};   // shank plate, inboard face")
    w(f"PLATE_T     = {plate_t:.1f};   // thigh plate thickness")
    w(f"SHANK_T     = {shank_t:.1f};    // shank plate thickness")
    w(f"HIP_COLLAR_H  = {hip_collar_h:.1f};  // pitch journal engagement")
    w(f"KNEE_COLLAR_H = {knee_collar_h:.1f};  // knee journal engagement")
    w(f"ROLL_GAP    = {gap:.1f};    // roll collar -> thigh plate, sets the leg plane")
    w("")

    # ---------------------------------------------------------------
    # SHANK SECTION
    #
    # The sketch had a thin shank because a lever carried it. There is
    # no lever now -- the knee is direct drive -- so the shank is a
    # cantilever and has to be a beam in its own right.
    #
    # Worst case is a sideways scuff at the foot: half the robot's
    # weight on one leg, 130 mm of lever arm.
    # ---------------------------------------------------------------
    f_side = c.mass * 9.81 / 2          # N, one leg takes half the robot
    moment = f_side * c.shank            # N.m at the knee
    w("// ---------------------------------------------------------------")
    w("// SHANK SECTION -- a tapered plate, SHANK_T thick. Sized for a")
    w(f"// sideways scuff at the foot: {f_side:.1f} N over {c.shank*M:.0f} mm")
    w(f"// = {moment:.2f} N.m at the knee. Stresses below are printed by")
    w("// check_walls.py; PETG yields near 50 MPa, derate to ~30 across")
    w("// the layer lines.")
    w("// ---------------------------------------------------------------")
    w(f"SHANK_W_KNEE = {shank_w_knee:.1f};  // width just below the knee collar")
    w(f"SHANK_W_FOOT = {shank_w_foot:.1f};  // width at the ankle")
    w(f"FOOT_R       = {foot_r:.1f};   // foot ball radius")
    w("")

    # ---------------------------------------------------------------
    # LEG PLAN -- the outline the thigh and shank are drawn to. These
    # used to live in leg.scad with a second copy in check_walls.py, so
    # the audit was reporting on a thigh that no longer existed.
    # ---------------------------------------------------------------
    w("// ---------------------------------------------------------------")
    w("// LEG PLAN -- outline radii. One copy, read by leg.scad and by")
    w("// check_walls.py, so the audit cannot report on a stale shape.")
    w("// ---------------------------------------------------------------")
    w(f"JOINT_BORE_D = {joint_bore_d:.1f};   // collar runs in this bore")
    w(f"HEAD_R       = {head_r:.1f};   // thigh plate, hip end")
    w(f"KNEE_R       = {knee_r:.1f};   // thigh plate, knee end  (also the")
    w("                      //   shank's collar end)")
    w(f"TRUSS_RAIL   = {truss_rail:.1f};  // web left between truss triangles")
    w(f"TRUSS_FILLET = {truss_fillet:.1f};  // corner radius inside the truss")
    w("")

    # ---------------------------------------------------------------
    # STANDING POSE -- straight out of the IK, so the assembly can
    # never be drawn in a pose the controller cannot command.
    # ---------------------------------------------------------------
    # ---------------------------------------------------------------
    # KNEE LINKAGE -- straight out of quadruped/transmission.py, so the
    # drawn mechanism and the one the controller solves are the same one.
    # ---------------------------------------------------------------
    link_a = TX.LINK_A * M
    link_d = TX.LINK_D * M
    link_phi = math.degrees(TX.LINK_PHI)
    crank_c = c.thigh*M - link_d             # crank axis, down from the hip
    # The whole mechanism rests on this: rod length == crank axis to knee
    # axis. Then the rod stays parallel to the thigh and the rocker stays
    # parallel to the crank, which is what makes the ratio exactly 1.
    assert abs(crank_c + link_d - c.thigh*M) < 1e-9
    if link_d >= c.thigh*M - 20.0:
        raise SystemExit(
            f"LINK_D {link_d:.1f} mm leaves only {c.thigh*M-link_d:.1f} mm of "
            f"thigh above the crank axis -- no room for the servo.")
    # Crank and rocker share a plane, so their swept discs must not.
    link_tip_r = 6.0                         # rounded end of each arm
    if 2 * (link_a + link_tip_r) >= link_d:
        raise SystemExit(
            f"crank and rocker sweep overlapping discs: "
            f"2*({link_a:.1f}+{link_tip_r:.1f}) must stay under LINK_D "
            f"({link_d:.1f} mm).")
    # And the crank's sweep must clear the pitch servo's body at the hip.
    reach = min(
        math.hypot(crank_c + link_a*math.cos(math.radians(t)),
                   link_a*math.sin(math.radians(t)))
        for t in [math.degrees(TX.crank_angle(TX.KNEE_RANGE[0]))
                  + i*(math.degrees(TX.crank_angle(TX.KNEE_RANGE[1]))
                       - math.degrees(TX.crank_angle(TX.KNEE_RANGE[0])))/120
                  for i in range(121)])
    hip_keepout = 35.0
    if reach - link_tip_r < hip_keepout:
        raise SystemExit(
            f"crank sweeps to {reach-link_tip_r:.1f} mm of the hip; the pitch "
            f"servo needs {hip_keepout:.0f} mm. Shorten LINK_D or LINK_A.")
    rod_force = 1.088 / TX.LINK_A            # N, at worst-case knee torque
    margin = min(math.degrees(TX.dead_point_margin(
        TX.KNEE_RANGE[0] + i * (TX.KNEE_RANGE[1] - TX.KNEE_RANGE[0]) / 200))
        for i in range(201))

    # The shoulder's arm reaches this far from the roll axis, so the
    # chassis has to be cut back that much where the arm sweeps past.
    sweep_clr, shell_z = 25.0, 20.0 + 2*3.0
    # arm_y0 = -12: the tongue spans the WHOLE bolt circle.
    #
    # At 0 it reached the axis and stopped, so it covered only half the
    # horn's 15 mm circle. Two of the four screws ran down the open
    # side of it and one sat right on the edge -- so three of the four
    # broke out through a curved or angled surface instead of landing
    # on a flat face, and only one had a seat at all. Carrying it 12 mm
    # past the axis puts all four inside solid material, emerging
    # together on the one flat face at the tongue's outer end.
    #
    # Free, again, for the same reason as before: the swept radius is
    # hypot(arm_y1, arm_t/2) and the far corner is still the one at
    # arm_y1, so the chassis cuts exactly the same room. The new
    # material sits at radius 16 where the envelope is 25.6.
    #
    # It is also the single biggest section the arm has had: 22 x 22
    # becomes 34 x 22.
    #
    # It was 12, to clear the roll servo's 20 mm width -- and that is a
    # real constraint where the arm crosses the axis, but the tongue
    # does not. The servo's body ends 7 mm out along the axis and the
    # tongue starts at 11, past it, so nothing was there.
    #
    # It matters because the TONGUE RUNS ALONG X. Its section is
    # (arm_y1 - arm_y0) by arm_t, so that 12 was not a position, it was
    # 12 mm taken straight out of the section carrying the leg: 10 x 22
    # where it could be 22 x 22. The rail met the 42 mm boss over a 10
    # mm band on its rim, which is the small L holding the arm on.
    #
    # Free, too: the swept radius is hypot(arm_y1, arm_t/2) and depends
    # on the OUTER edge only, so the chassis cuts exactly the same room.
    arm_y0, arm_y1 = -12.0, 22.0
    # Radius ABOUT the roll axis, which is the x axis -- so it is the
    # arm's y and z that matter, not how far along x it reaches.
    # Using the x extent gave 36.5 mm instead of 26.6 and cut the rear
    # servo mounts clean off the chassis: 4 cm3 of loose plastic a side.
    #
    # Only the tongue counts. The outer rail lives past y = 22 and the
    # chassis stops 21 mm out from the roll axis, so even rolled over
    # 30 degrees the rail never reaches it.
    # The tongue is shallower than the housing. At the housing's full
    # 26 mm it reached exactly down to the chassis plate at zero roll,
    # and through it at any roll at all.
    # 22. The tongue is centred on the roll axis at HIP_Z = 21, so its
    # depth is bounded by the chassis plate 8 mm below: at the housing's
    # full 26 it reaches exactly z = 8 and goes through the plate at any
    # roll at all. 22 stops at z = 10, and it also cuts the step where
    # the tongue meets the long run from 10 mm down to 4.
    # 24, for the land under the horn screws. The two at the top and
    # bottom of the bolt circle sit 7.5 mm out, and an M3 head is 5.5
    # across -- so in a tongue 11 mm deep its edge landed 0.75 mm from
    # the tongue's own edge. True at 22, and 1.75 mm at 24.
    #
    # (The 97.2% a seat probe reported at 22 was NOT that. It read the
    #  same at 24 and the same at all four screws, because it was the
    #  axis access bore clipping the inner lip of an oversized probe
    #  ring. Measured against a real 5.5 mm head, every one of the
    #  four bears on 100% of its annulus. The depth is still worth
    #  having; the number that prompted it was measuring something
    #  else.)
    #
    # Still short of the housing's 26, which is the real stop: the
    # tongue is centred on the roll axis 21 mm up, so at 26 its lower
    # face reaches z = 8 and goes straight through the chassis plate.
    # 24 stops at 9.
    arm_t = 24.0
    sweep_r = math.hypot(arm_y1, arm_t/2) + 1.0
    w("// ---------------------------------------------------------------")
    w("// SHOULDER ARM. One copy, read by shoulder.scad (which draws the")
    w("// arm) and by chassis.scad (which has to cut room for it). They")
    w("// used to each keep their own: the chassis was still cutting for")
    w("// a 26 mm arm after the real one had grown past 33.")
    w("//")
    w("// ARM_Y0/ARM_Y1 is the band the arm crosses the thigh's plane in.")
    w("// It is pinned between the roll servo's 20 mm width (so the arm")
    w("// can pass in front of it on the rear legs) and the thigh plate.")
    w("// ---------------------------------------------------------------")
    w(f"SWEEP_CLR        = {sweep_clr:.1f};   // arm's offset from the roll axis")
    w(f"SHELL_Z          = {shell_z:.1f};   // arm and housing depth")
    w(f"ARM_Y0           = {arm_y0:.1f};   // arm leaves the boss here")
    w(f"ARM_Y1           = {arm_y1:.1f};")
    w(f"ARM_T            = {arm_t:.1f};   // tongue depth, shallower than the housing")
    w(f"SHOULDER_SWEEP_R = {sweep_r:.1f};   // how much chassis to cut away")
    w("")

    w("// ---------------------------------------------------------------")
    w("// KNEE LINKAGE -- a parallelogram. Crank and rocker are the SAME")
    w("// length and the rod equals the crank-to-knee distance; that is")
    w("// what makes the ratio exactly 1.0 instead of a general four-bar's")
    w("// 0.12 worst case. Change one of the three and the others must")
    w("// follow, so they come from transmission.py and are not typed.")
    w("//")
    w(f"// rod carries {rod_force:.0f} N at 1.09 N.m of knee torque")
    w(f"// crank stays {margin:.1f} deg clear of a dead point")
    w("// ---------------------------------------------------------------")
    w(f"LINK_A    = {link_a:.1f};    // crank AND rocker length")
    w(f"LINK_D    = {link_d:.1f};    // crank axis -> knee axis, AND rod length")
    w(f"LINK_PHI  = {link_phi:.1f};  // shank -> rocker, fixed")
    w(f"CRANK_C   = {crank_c:.1f};    // crank axis, measured down the thigh")
    w(f"LINK_T    = {link_out-link_in:.1f};     // crank and rocker plate thickness")
    w(f"LINK_TIP_R = {link_tip_r:.1f};   // rounded end on each arm")
    w(f"ROD_T     = {rod_t:.1f};     // pushrod thickness")
    w("// EVERY LINKAGE PIVOT IS A SHOULDER BOLT, not a screw.")
    w("//")
    w("// A screw through both parts pulls them together and the joint")
    w("// stops being a joint. A shoulder bolt has a plain 4 mm shank")
    w("// that is LONGER than the rod is thick, so the rod turns on the")
    w("// shank while the thread pulls the shoulder's end face down onto")
    w("// the arm. The clamp load never reaches the rod.")
    w("//")
    w("//   rod end     4.2 mm clearance -- it must be free to turn")
    w("//   arm end     M3 heat-set insert, PIVOT_INSERT_H deep")
    w("//   bolt        M3 thread, 4 mm shoulder, 6 mm long against a")
    w("//               5 mm rod: 1 mm of end float, plus a washer")
    w("PIVOT_BOLT_D   = 4.0;   // the shoulder itself")
    w("PIVOT_ROD_D    = 4.2;   // clearance for it in the rod")
    w("PIVOT_INSERT_H = 6.0;")
    w("PIVOT_D   = 3.4;    // M3 clearance, where something IS meant to clamp")
    w(f"CRANK_SWEEP = [{math.degrees(TX.crank_angle(TX.KNEE_RANGE[0])):.1f}, "
      f"{math.degrees(TX.crank_angle(TX.KNEE_RANGE[1])):.1f}];  // from the thigh line")
    w("")

    w("// ---------------------------------------------------------------")
    w("// STANDING POSE -- solved by quadruped.robot, not typed. The")
    w("// assembly renders in a pose the controller can actually hold,")
    w("// and FOOT_* is where that pose must put the foot.")
    w("// ---------------------------------------------------------------")
    w(f"POSE_ROLL = {math.degrees(pose_a.roll):.3f};")
    w(f"POSE_HIP  = {math.degrees(pose_a.hip):.3f};")
    w(f"POSE_KNEE = {math.degrees(pose_a.knee):.3f};")
    w(f"FOOT_X    = {foot[0]*M:.3f};   // from the roll axis, in the leg frame")
    w(f"FOOT_Y    = {foot[1]*M:.3f};")
    w(f"FOOT_Z    = {foot[2]*M:.3f};")
    w("")

    w("// ---------------------------------------------------------------")
    w("// IDLER BEARING -- the second support on every joint.")
    w("//")
    w("// The DS3225 has only one output shaft, so each joint gets a")
    w("// printed bearing boss opposite it. Without this the servo's own")
    w("// output bearing carries the full bending moment (1.17 N.m at the")
    w("// knee) in a direction it was never specified for, and the joint")
    w("// develops play. 624ZZ runs on an M4 bolt: cheap, common, and the")
    w("// bolt is a far better shaft than printed plastic.")
    w("// ---------------------------------------------------------------")
    w("BEARING_OD = 13.0;  // 624ZZ")
    w("BEARING_ID =  4.0;")
    w("BEARING_TH =  5.0;")
    w("BEARING_FIT = 0.05; // press fit: negative clearance, tighten if loose")
    w("")
    w("// ---------------------------------------------------------------")
    w("// PRINT -- tuned for PETG. PLA creeps under sustained load and the")
    w("// legs are loaded whenever the robot is switched on.")
    w("// ---------------------------------------------------------------")
    w("WALL      = 3.0;   // structural wall thickness")
    w("CLEAR     = 0.3;   // clearance on parts that must slide or rotate")
    w("M3_CLEAR  = 3.4;   // M3 through-hole")
    w("M3_INSERT = 4.0;   // M3 heat-set insert pilot hole  <-- CHECK YOURS")
    w("M4_CLEAR  = 4.5;")
    w("M4_INSERT = 5.6;   // M4 heat-set insert pilot  <-- CHECK YOURS")
    w("FILLET    = 2.0;")
    w("$fn = 48;")
    w("")

    out.write_text("\n".join(L))
    print(f"wrote {out}")
    print()
    print("Kinematic values locked to the controller:")
    print(f"  hip offset {c.hip_offset*M:.1f} mm")
    print(f"  thigh      {c.thigh*M:.1f} mm")
    print(f"  shank      {c.shank*M:.1f} mm")
    print(f"  body       {c.body_length*M:.0f} x {c.body_width*M:.0f} mm")
    print()
    print("Hip positions in the body frame (for the chassis plate):")
    for n in LEG_NAMES:
        o = robot.legs[n].origin
        print(f"  {n}  ({o.x*M:+7.1f}, {o.y*M:+7.1f})")


